def translate_schedule_wizard(language: str | None, key: str, **values: object) -> str:
    locale = normalize_language(language)
    template = _MESSAGES.get(locale, _MESSAGES[DEFAULT_LANGUAGE]).get(
        key, _MESSAGES[DEFAULT_LANGUAGE].get(key, key)
    )
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


