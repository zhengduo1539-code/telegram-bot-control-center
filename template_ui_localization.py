def _placeholder_fields(message: str) -> set[str]:
    return {field_name for _, field_name, _, _ in Formatter().parse(message) if field_name}


def translate_template_ui(language: str | None, key: str, **values: Any) -> str:
    """Translate shared template/queue UX copy with a safe English fallback."""
    locale = normalize_language(language)
    message = TRANSLATIONS.get(locale, TRANSLATIONS[DEFAULT_LANGUAGE]).get(
        key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    )
    try:
        return message.format(**values)
    except (KeyError, ValueError, IndexError):
        return message
